"""Regenerate src/engines/colormaps/cmocean.lut.ts from the published cmocean tables.

Usage: python -m venv .venv && .venv/bin/pip install cmocean && .venv/bin/python scripts/gen-luts.py
Sampling cm(i/255) for i in 0..255 is the same 256-entry table the solver uses for its PNGs.
"""
import pathlib

import cmocean

OUT = pathlib.Path(__file__).resolve().parent.parent / "src/engines/colormaps/cmocean.lut.ts"


def to_hex(name: str) -> str:
    cmap = getattr(cmocean.cm, name)
    rows = []
    for i in range(256):
        r, g, b, _ = cmap(i / 255)
        rows.append("%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255)))
    return "".join(rows)


def chunk(s: str, n: int = 96) -> str:
    return "\n".join(f'  "{s[i:i + n]}" +' for i in range(0, len(s), n)).rstrip(" +")


body = [
    f"// Generated by scripts/gen-luts.py from cmocean {cmocean.__version__}. Do not edit by hand.",
    "/** cmocean.speed, 256 RGB entries as concatenated hex. */",
    "export const SPEED_HEX =\n" + chunk(to_hex("speed")) + ";",
    "/** cmocean.balance, 256 RGB entries as concatenated hex. */",
    "export const BALANCE_HEX =\n" + chunk(to_hex("balance")) + ";",
    "",
]
OUT.write_text("\n".join(body))
print("wrote", OUT)
